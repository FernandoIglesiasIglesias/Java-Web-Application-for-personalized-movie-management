CREATE TABLE IF NOT EXISTS Users (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    userName VARCHAR(60) NOT NULL,
    password VARCHAR(60) NOT NULL, 
    email VARCHAR(60) NOT NULL, 
    avatar VARCHAR(255) NOT NULL,
    role TINYINT NOT NULL,
    CONSTRAINT UserPK PRIMARY KEY (id),
    CONSTRAINT UserNameUniqueKey UNIQUE (userName),
    CONSTRAINT EmailUniqueKey UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS Movies (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    title VARCHAR(255) NOT NULL,
    synopsis TEXT,
    duration INT,
    genre TINYINT NOT NULL,
    CONSTRAINT MoviePK PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS Actors (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    firstName VARCHAR(60) NOT NULL,
    lastName VARCHAR(60) NOT NULL,
    nationality VARCHAR(60),
    birthDate DATE,
    CONSTRAINT ActorPK PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS Directors (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    firstName VARCHAR(60) NOT NULL,
    lastName VARCHAR(60) NOT NULL,
    nationality VARCHAR(60),
    birthDate DATE,
    CONSTRAINT DirectorPK PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS MovieActors (
    movieId BIGINT NOT NULL,
    actorId BIGINT NOT NULL,
    CONSTRAINT MovieActorPK PRIMARY KEY (movieId, actorId),
    CONSTRAINT MovieFK FOREIGN KEY (movieId) REFERENCES Movies(id),
    CONSTRAINT ActorFK FOREIGN KEY (actorId) REFERENCES Actors(id)
);

CREATE TABLE IF NOT EXISTS MovieDirectors (
    movieId BIGINT NOT NULL,
    directorId BIGINT NOT NULL,
    CONSTRAINT MovieDirectorPK PRIMARY KEY (movieId, directorId),
    CONSTRAINT MovieFK FOREIGN KEY (movieId) REFERENCES Movies(id),
    CONSTRAINT DirectorFK FOREIGN KEY (directorId) REFERENCES Directors(id)
);